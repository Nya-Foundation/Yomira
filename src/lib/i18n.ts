const DICTS: Record<Locale, Record<TKey, string>> = { en, "zh-CN": zh };

export type TVars = Record<string, string | number>;
export type TFunction = (key: TKey, vars?: TVars) => string;

/** Effective OS/webview locale, mapped to the closest supported locale. */
export function systemLocale(): Locale {
  const lang = typeof navigator !== "undefined" ? navigator.language : "en";
  return lang.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}

/** The locale currently in effect (settings preference, or system locale). */
export function currentLocale(): Locale {
  const pref = useSettings.getState().settings.language;
  if (pref === "en" || pref === "zh-CN") return pref;
  return systemLocale();
}

/** Translate a key, interpolating `{var}` placeholders. Works outside React. */
export const t: TFunction = (key, vars) => {
  let s: string = DICTS[currentLocale()][key];
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.split(`{${k}}`).join(String(v));
    }
  }
  return s;
};

/**
 * Hook form of `t()`. Subscribes to the language setting so the component
 * re-renders (in the new language) whenever it changes.
 */
export function useT(): TFunction {
  const language = useSettings((s) => s.settings.language);
  return useCallback(t, [language]);
}

/** Keeps `document.documentElement.lang` in sync with the effective locale. */
export function I18nProvider({ children }: { children: ReactNode }) {
  const language = useSettings((s) => s.settings.language);
  useEffect(() => {
    document.documentElement.lang = currentLocale();
  }, [language]);
  return children;
}

/** Localized display name for a gallery category (English name is the data key). */
export function categoryLabel(category: Category): string {
  return currentLocale() === "zh-CN" ? ZH_CATEGORY_NAMES[category] : category;
}
